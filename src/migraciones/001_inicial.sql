-- Cada tabla de datos de cliente lleva tienda_id: varias tiendas conviven en la misma base.

-- Fecha y hora UTC como texto "2026-11-12 01:03:25": las columnas de fecha son TEXT y se ordenan y comparan como texto.
CREATE FUNCTION ahora() RETURNS text AS $$
  SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
$$ LANGUAGE sql STABLE;

-- Igual que slugificar() de src/util/slug.js: sin tildes ni eñes, en minúsculas y con guiones.
-- Se usa en SQL para buscar sin importar tildes ni mayúsculas (lower() depende de la configuración regional del servidor).
CREATE FUNCTION slugificar(texto text) RETURNS text AS $$
  SELECT trim(both '-' from regexp_replace(
    lower(translate(coalesce(texto, ''),
      'ÁÀÂÄÃÅĀÉÈÊËĒÍÌÎÏĪÓÒÔÖÕØŌÚÙÛÜŪÑÇÝáàâäãåāéèêëēíìîïīóòôöõøōúùûüūñçýÿ',
      'AAAAAAAEEEEEIIIIIOOOOOOOUUUUUNCYaaaaaaaeeeeeiiiiiooooooouuuuuncyy')),
    '[^a-z0-9]+', '-', 'g'))
$$ LANGUAGE sql IMMUTABLE;

CREATE TABLE tiendas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  creada_en TEXT NOT NULL DEFAULT ahora()
);

CREATE TABLE usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  email TEXT NOT NULL,
  hash_clave TEXT NOT NULL,
  creado_en TEXT NOT NULL DEFAULT ahora()
);
-- El email es único sin importar mayúsculas ("Ana@x.com" y "ana@x.com" son la misma cuenta).
CREATE UNIQUE INDEX usuarios_email_unico ON usuarios (lower(email));

CREATE TABLE categorias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  padre_id INTEGER REFERENCES categorias(id),
  nombre TEXT NOT NULL,
  slug TEXT NOT NULL
);
-- coalesce: las categorías raíz tienen padre NULL, y dos NULL no chocan en un UNIQUE.
CREATE UNIQUE INDEX categorias_unicas ON categorias (tienda_id, coalesce(padre_id, 0), slug);

CREATE TABLE productos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  slug TEXT NOT NULL,
  nombre TEXT NOT NULL,
  descripcion TEXT NOT NULL DEFAULT '',
  marca TEXT NOT NULL DEFAULT '',
  atributo1 TEXT,
  atributo2 TEXT,
  atributo3 TEXT,
  visible INTEGER NOT NULL DEFAULT 1,
  creado_en TEXT NOT NULL DEFAULT ahora(),
  actualizado_en TEXT NOT NULL DEFAULT ahora(),
  UNIQUE (tienda_id, slug)
);

CREATE TABLE producto_categorias (
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE CASCADE,
  PRIMARY KEY (producto_id, categoria_id)
);

-- Los precios van en centavos, en BIGINT: en pesos argentinos se pasan fácil de los 2.147 millones de un INTEGER.
CREATE TABLE variantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  sku TEXT NOT NULL,
  valor1 TEXT,
  valor2 TEXT,
  valor3 TEXT,
  precio_centavos BIGINT NOT NULL CHECK (precio_centavos > 0),
  precio_promocional_centavos BIGINT CHECK (precio_promocional_centavos > 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  peso_kg DOUBLE PRECISION,
  alto_cm DOUBLE PRECISION,
  ancho_cm DOUBLE PRECISION,
  profundidad_cm DOUBLE PRECISION,
  creado_en TEXT NOT NULL DEFAULT ahora(),
  actualizado_en TEXT NOT NULL DEFAULT ahora(),
  UNIQUE (tienda_id, sku)
);
CREATE INDEX variantes_por_producto ON variantes (producto_id);

CREATE TABLE sesiones (
  sid TEXT PRIMARY KEY,
  datos TEXT NOT NULL,
  expira BIGINT NOT NULL
);
