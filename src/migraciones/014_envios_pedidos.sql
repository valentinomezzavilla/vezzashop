-- Seguimiento de los pedidos con envío a domicilio y su historial.
--
-- El estado general del pedido (nuevo, pagado, enviado, entregado, cancelado) sigue siendo el de siempre: lo usan los filtros, el stock y
-- cancelar. Para los pedidos a domicilio, envio_estado lo afina: preparacion -> despachado -> en_camino -> entregado (NULL: todavía no se
-- empezó). Retiro en el local no usa envio_estado.
--  envio_empresa / envio_seguimiento / envio_enlace: con quién se mandó, el número de seguimiento y el link para seguirlo (opcional).
--  envio_detalle: una aclaración para el cliente, por ejemplo "Llega entre el 12 y el 14".
--  nota_interna: solo la ve la tienda.
ALTER TABLE pedidos ADD COLUMN envio_estado TEXT CHECK (envio_estado IN ('preparacion', 'despachado', 'en_camino', 'entregado'));
ALTER TABLE pedidos ADD COLUMN envio_empresa TEXT NOT NULL DEFAULT '';
ALTER TABLE pedidos ADD COLUMN envio_seguimiento TEXT NOT NULL DEFAULT '';
ALTER TABLE pedidos ADD COLUMN envio_enlace TEXT NOT NULL DEFAULT '';
ALTER TABLE pedidos ADD COLUMN envio_detalle TEXT NOT NULL DEFAULT '';
ALTER TABLE pedidos ADD COLUMN nota_interna TEXT NOT NULL DEFAULT '';

-- Los pedidos a domicilio que ya estaban enviados o entregados quedan en el paso que les corresponde.
UPDATE pedidos SET envio_estado = 'despachado' WHERE entrega_tipo = 'domicilio' AND estado = 'enviado';
UPDATE pedidos SET envio_estado = 'entregado' WHERE entrega_tipo = 'domicilio' AND estado = 'entregado';

-- Cada movimiento de un pedido (lo recibimos, se pagó, se despachó...). visible_cliente: si lo ve el comprador en la página de su pedido
-- (las correcciones, como volver un pedido atrás por un error, no). avisado_email: si se le mandó el mail con ese movimiento.
-- paso: a qué paso de la línea de tiempo corresponde (recibido, pagado, preparacion, despachado, en_camino, listo, entregado, cancelado).
CREATE TABLE pedido_eventos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INTEGER NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  paso TEXT NOT NULL,
  titulo TEXT NOT NULL,
  detalle TEXT NOT NULL DEFAULT '',
  visible_cliente INTEGER NOT NULL DEFAULT 1,
  avisado_email INTEGER NOT NULL DEFAULT 0,
  creado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE INDEX pedido_eventos_por_pedido ON pedido_eventos (pedido_id, id);

