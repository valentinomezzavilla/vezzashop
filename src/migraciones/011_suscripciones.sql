-- Suscripciones a los planes (débito automático con Mercado Pago) y titular de cada cuenta.
--
-- Una suscripción nace antes que la tienda: el visitante elige un plan, paga, y recién ahí completa el formulario que crea su
-- cuenta. Por eso tienda_id empieza vacío y se llena al crear la cuenta (o, si la suscripción es de un cliente que ya existe,
-- nace con su tienda). El link para completar el formulario no se guarda: se calcula a partir del id (ver suscripciones.js).
CREATE TABLE suscripciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER REFERENCES tiendas(id),
  plan_id INTEGER NOT NULL REFERENCES planes(id),
  mp_id TEXT UNIQUE,                                   -- id de la suscripción en Mercado Pago (vacío en la prueba gratis)
  estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'autorizada', 'pausada', 'cancelada', 'prueba')),
  monto_centavos BIGINT NOT NULL DEFAULT 0 CHECK (monto_centavos >= 0),   -- lo que se cobra por mes, el del plan al suscribirse
  email_pagador TEXT NOT NULL,
  proximo_cobro TEXT,                                  -- "2026-12-31"
  aviso_pago_enviado_en TEXT,                          -- cuándo se mandó el mail "pagaste, creá tu cuenta"
  enlace_renovado_en TEXT,                             -- si se reenvió el link, el plazo de 14 días cuenta desde acá
  reemplaza_a_id INTEGER REFERENCES suscripciones(id), -- cambio de plan: la suscripción anterior, que se cancela al autorizarse esta
  creada_en TEXT NOT NULL DEFAULT ahora(),
  actualizada_en TEXT NOT NULL DEFAULT ahora()
);
CREATE INDEX suscripciones_por_tienda ON suscripciones (tienda_id);

-- Cada cobro aprobado. mp_cobro_id único: si Mercado Pago avisa dos veces el mismo cobro, se suma un solo mes.
-- aplicado_en vacío: el cliente pagó pero todavía no creó su cuenta; se aplica cuando la cree.
CREATE TABLE suscripcion_cobros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  suscripcion_id INTEGER NOT NULL REFERENCES suscripciones(id),
  mp_cobro_id TEXT NOT NULL UNIQUE,
  monto_centavos BIGINT NOT NULL DEFAULT 0,
  aprobado_en TEXT NOT NULL DEFAULT ahora(),
  aplicado_en TEXT
);
CREATE INDEX suscripcion_cobros_por_suscripcion ON suscripcion_cobros (suscripcion_id);

