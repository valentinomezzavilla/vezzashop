-- Kit de marca y maquetas web (plan Acompañado): el cliente sube el material de su marca y n8n genera una maqueta de su tienda.
-- Nada de esto cambia la vidriera: es el material de la maqueta y su resultado.

-- Lo que la tienda cuenta de su marca. Una fila por tienda; sin fila, todo vacío.
-- Los colores son #rrggbb, o '' si no se eligió (el principal vacío usa el color principal de Diseño).
CREATE TABLE marca (
  tienda_id INTEGER PRIMARY KEY REFERENCES tiendas(id),
  color_principal TEXT NOT NULL DEFAULT '',
  color_secundario TEXT NOT NULL DEFAULT '',
  color_acento TEXT NOT NULL DEFAULT '',
  rubro TEXT NOT NULL DEFAULT '',
  estilo TEXT NOT NULL DEFAULT '',
  descripcion TEXT NOT NULL DEFAULT '',
  referencias TEXT NOT NULL DEFAULT '',
  actualizado_en TEXT NOT NULL DEFAULT ahora()
);

-- Los logos y las fotos que sube. `archivo` es el nombre en la carpeta de subidas de la tienda (como las fotos de los productos);
-- `nombre` es el que tenía el archivo en la computadora del cliente, solo para mostrárselo.
CREATE TABLE marca_archivos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  tipo TEXT NOT NULL CHECK (tipo IN ('logo', 'foto')),
  archivo TEXT NOT NULL,
  nombre TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE INDEX marca_archivos_por_tienda ON marca_archivos (tienda_id, id);

-- Cada pedido de maqueta y su resultado.
--  estado: pendiente (se le avisó a n8n) -> generando (n8n empezó) -> lista (llegó el HTML) | error.
--  token_hash: SHA-256 del token de ese pedido. El token viaja una sola vez, en el aviso a n8n; n8n lo devuelve para entregar el resultado,
--  así que solo quien recibió el pedido puede completarlo.
--  html: la maqueta ya limpia (src/maquetas.js la deja solo con lo permitido). resumen y error son textos cortos para mostrar.
CREATE TABLE maquetas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'generando', 'lista', 'error')),
  token_hash TEXT NOT NULL,
  html TEXT,
  resumen TEXT NOT NULL DEFAULT '',
  error TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT ahora(),
  actualizado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE INDEX maquetas_por_tienda ON maquetas (tienda_id, id DESC);
-- Una sola maqueta en camino por tienda: aunque lleguen dos pedidos a la vez, la base rechaza el segundo.
CREATE UNIQUE INDEX maquetas_una_en_curso ON maquetas (tienda_id) WHERE estado IN ('pendiente', 'generando');
