-- Administración de la plataforma: planes, estado y vencimiento de cada cliente, pagos y cuentas de superadministrador.

-- Un plan fija los topes de una tienda. NULL en un tope = sin límite.
CREATE TABLE planes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  precio_centavos BIGINT NOT NULL DEFAULT 0 CHECK (precio_centavos >= 0),   -- por mes
  max_productos INTEGER CHECK (max_productos > 0),
  max_fotos INTEGER CHECK (max_fotos BETWEEN 1 AND 10),                      -- por producto
  max_banners INTEGER CHECK (max_banners BETWEEN 0 AND 6),
  activo INTEGER NOT NULL DEFAULT 1,                                         -- 0: ya no se ofrece, pero los clientes que lo tienen lo conservan
  creado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE UNIQUE INDEX planes_por_nombre ON planes (lower(nombre));

-- Las tiendas que ya existían quedan en un plan sin topes, para que nada cambie para ellas.
INSERT INTO planes (nombre) VALUES ('Sin límites');

-- plan_id NULL (por ejemplo, una tienda creada sin plan) vale como "sin límites".
ALTER TABLE tiendas ADD COLUMN plan_id INTEGER REFERENCES planes(id);
UPDATE tiendas SET plan_id = (SELECT id FROM planes WHERE nombre = 'Sin límites');
ALTER TABLE tiendas ADD COLUMN estado TEXT NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'suspendida'));
ALTER TABLE tiendas ADD COLUMN motivo_suspension TEXT NOT NULL DEFAULT '';   -- nota interna: no la ven los compradores
ALTER TABLE tiendas ADD COLUMN vence_en TEXT;                                -- "2026-12-31"; NULL: sin vencimiento
ALTER TABLE tiendas ADD COLUMN notas TEXT NOT NULL DEFAULT '';               -- notas internas del administrador

-- Cada cobro que el administrador registra a mano: extiende el vencimiento.
CREATE TABLE pagos_plataforma (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES tiendas(id),
  monto_centavos BIGINT NOT NULL DEFAULT 0 CHECK (monto_centavos >= 0),
  meses INTEGER NOT NULL CHECK (meses > 0),
  vencia_antes TEXT,
  vence_despues TEXT NOT NULL,
  nota TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE INDEX pagos_plataforma_por_tienda ON pagos_plataforma (tienda_id, id);

-- Cuentas del administrador de la plataforma. Van aparte de los usuarios de las tiendas: no pertenecen a ninguna.
CREATE TABLE superadmins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  hash_clave TEXT NOT NULL,
  creado_en TEXT NOT NULL DEFAULT ahora()
);
CREATE UNIQUE INDEX superadmins_por_email ON superadmins (lower(email));
